"""Render the layer-legend screens and write them as LVGL images for the right-hand nice!view.

    python3 build_legend.py

Writes ../boards/shields/nice_view_legend/widgets/legend_art.c. The firmware draws the
battery/link bar in the top 20px itself, so only the 68x140 area below it is exported.
"""
import os
from lvimg import portrait_to_native, decode_c_array
from concepts import legend_idle, legend_layer1, legend_layer2

OUT = os.path.join(os.path.dirname(__file__), '..', 'boards', 'shields', 'nice_view_legend',
                   'widgets', 'legend_art.c')
SCREENS = [
    ('legend_base', legend_idle, 'Layer 0: name and mini Sofle'),
    ('legend_l1', legend_layer1, 'Layer 1: navigation, symbols, F-keys, mouse, RGB'),
    ('legend_l2', legend_layer2, 'Layer 2: Bluetooth, output, flash, restart, soft off'),
]
ART_TOP = 20  # first portrait row not covered by the status bar


def art_region(portrait):
    return portrait_to_native(portrait.crop((0, ART_TOP, portrait.width, portrait.height)))


def encode(native):
    """LV_IMG_CF_INDEXED_1BIT rows, MSB first; ink -> index 0 (matches the stock art)."""
    w, h = native.size
    stride = (w + 7) // 8
    px = native.load()
    data = []
    for y in range(h):
        for bx in range(stride):
            b = 0
            for bit in range(8):
                x = bx * 8 + bit
                b = (b << 1) | (1 if x >= w or not px[x, y] else 0)
            data.append(b)
    return data


def c_image(name, comment, native):
    data = encode(native)
    rows = []
    for i in range(0, len(data), 18):
        rows.append('        ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 18]) + ',')
    attr = 'LV_ATTRIBUTE_IMG_' + name.upper()
    return f'''/* {comment} */
#ifndef {attr}
#define {attr}
#endif

const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST {attr} uint8_t {name}_map[] = {{
#if CONFIG_NICE_VIEW_WIDGET_INVERTED
        0xff, 0xff, 0xff, 0xff, /*Color of index 0*/
        0x00, 0x00, 0x00, 0xff, /*Color of index 1*/
#else
        0x00, 0x00, 0x00, 0xff, /*Color of index 0*/
        0xff, 0xff, 0xff, 0xff, /*Color of index 1*/
#endif

{chr(10).join(rows)}
}};

const lv_img_dsc_t {name} = {{
    .header.cf = LV_IMG_CF_INDEXED_1BIT,
    .header.always_zero = 0,
    .header.reserved = 0,
    .header.w = {native.width},
    .header.h = {native.height},
    .data_size = {8 + len(data)},
    .data = {name}_map,
}};
'''


def main():
    parts = ['''/*
 * Generated by art/build_legend.py. Do not edit by hand; edit art/concepts.py and re-run.
 *
 * SPDX-License-Identifier: MIT
 */

#include <lvgl.h>

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif
''']
    natives = {}
    for name, fn, comment in SCREENS:
        natives[name] = art_region(fn())
        parts.append(c_image(name, comment, natives[name]))
    src = '\n'.join(parts)
    # round-trip check against the decoder used to verify the stock balloon
    for name, native in natives.items():
        back = decode_c_array(src, name)
        assert back.size == native.size and list(back.getdata()) == list(native.convert('1').getdata()), name
    with open(OUT, 'w') as f:
        f.write(src)
    print(f'wrote {os.path.normpath(OUT)}: ' + ', '.join(f'{n} {im.size[0]}x{im.size[1]}' for n, im in natives.items()))


if __name__ == '__main__':
    main()
