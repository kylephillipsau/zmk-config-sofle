"""Generate 1-bpp LVGL 8 fonts from TTFs with PIL, so on-device text matches the PIL mockups.

lv_font_conv only accepts whole-number sizes, but pixel fonts such as Jersey 10 sit on a grid
that needs fractional sizes (one font pixel = 1/18.67 em). Rendering with PIL at the exact size
keeps every glyph on whole pixels and identical to the mockups.

    python3 make_lvfont.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, '..', 'boards', 'shields', 'nice_view_legend', 'fonts')

ASCII = ''.join(chr(c) for c in range(0x20, 0x7F))
DIGITS = ' %-0123456789'

# (C name, TTF, size in px, characters)
FONTS = [
    ('lv_font_silkscreen_8', 'Silkscreen-Regular.ttf', 8, ASCII),
    ('lv_font_silkscreen_bold_8', 'Silkscreen-Bold.ttf', 8, ASCII),
    ('lv_font_jersey_1x', 'Jersey10-Regular.ttf', 56 / 3, ASCII),     # 10px capitals, 1:1 grid
    ('lv_font_jersey_2x', 'Jersey10-Regular.ttf', 112 / 3, DIGITS),   # 20px capitals, 2:1 grid
]


def glyph(font, ch, ascent, descent):
    """Return (bits, box_w, box_h, ofs_x, ofs_y, adv_px) using LVGL's glyph conventions."""
    pad = 8
    w = int(font.getlength(ch)) + 2 * pad + 8
    h = ascent + descent + 2 * pad
    img = Image.new('1', (w, h), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = '1'
    base = pad + ascent
    d.text((pad, base), ch, font=font, fill=1, anchor='ls')
    adv = font.getlength(ch)
    assert abs(adv - round(adv)) < 1e-6, f'{ch!r} advance {adv} is not on the pixel grid'
    bbox = img.getbbox()
    if not bbox:
        return [], 0, 0, 0, 0, round(adv)
    x0, y0, x1, y1 = bbox
    px = img.load()
    bits = [1 if px[x, y] else 0 for y in range(y0, y1) for x in range(x0, x1)]
    # ofs_y: glyph bottom relative to the baseline, positive upwards
    return bits, x1 - x0, y1 - y0, x0 - pad, base - y1, round(adv)


def generate(name, ttf, size, chars):
    font = ImageFont.truetype(os.path.join(HERE, 'fonts', ttf), size)
    ascent, descent = font.getmetrics()
    chars = sorted(set(chars), key=ord)
    bitmap, dscs, comments = [], [], []
    for ch in chars:
        bits, bw, bh, ox, oy, adv = glyph(font, ch, ascent, descent)
        start = len(bitmap)
        packed = [sum(b << (7 - i) for i, b in enumerate(bits[k:k + 8])) for k in range(0, len(bits), 8)] or [0]
        bitmap.extend(packed)
        dscs.append((start, adv * 16, bw, bh, ox, oy))
        comments.append((ch, packed))

    # contiguous ranges -> one FORMAT0_TINY cmap each
    ranges, gid = [], 1
    i = 0
    while i < len(chars):
        j = i
        while j + 1 < len(chars) and ord(chars[j + 1]) == ord(chars[j]) + 1:
            j += 1
        ranges.append((ord(chars[i]), j - i + 1, gid))
        gid += j - i + 1
        i = j + 1

    def esc(c):
        return {'"': "'\"'", '\\': "'\\\\'"}.get(c, c)

    lines = [f'/*\n * {name}: {ttf} at {size:.4g}px, 1 bpp.\n'
             ' * Generated by art/make_lvfont.py. Do not edit by hand.\n */\n',
             '#include <lvgl.h>\n',
             'static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {']
    for ch, packed in comments:
        lines.append(f'    /* U+{ord(ch):04X} "{esc(ch)}" */')
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in packed) + ',')
    lines.append('};\n')
    lines.append('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
    lines.append('    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,')
    for (bi, adv, bw, bh, ox, oy) in dscs:
        lines.append(f'    {{.bitmap_index = {bi}, .adv_w = {adv}, .box_w = {bw}, .box_h = {bh}, .ofs_x = {ox}, .ofs_y = {oy}}},')
    lines.append('};\n')
    lines.append('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
    for start, length, first in ranges:
        lines.append(f'    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {first}, '
                     '.unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, '
                     '.type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},')
    lines.append('};\n')
    lines.append('static lv_font_fmt_txt_glyph_cache_t cache;\n')
    lines.append(f'''static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(ranges)},
    .bpp = 1,
    .kern_classes = 0,
    .bitmap_format = 0,
    .cache = &cache,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = 0,
    .underline_thickness = 0,
    .dsc = &font_dsc,
}};
''')
    path = os.path.join(OUT_DIR, f'{name}.c')
    with open(path, 'w') as f:
        f.write('\n'.join(lines))
    return path


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for spec in FONTS:
        print('wrote', os.path.relpath(generate(*spec), HERE))


if __name__ == '__main__':
    main()
